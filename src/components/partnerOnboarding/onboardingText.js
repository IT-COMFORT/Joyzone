const TEXTS = { uz: UZ, ru: RU, en: EN };

export function useOnboardingText() {
  const { lang } = useLanguage();
  return { t: TEXTS[lang] || UZ, lang: TEXTS[lang] ? lang : "uz" };
}

// Picks name_uz / name_ru / name_en from an API object, with fallbacks.
export function pickLocalized(item, lang, field = "name") {
  if (!item) return "";
  return item[`${field}_${lang}`] || item[`${field}_ru`] || item[`${field}_uz`] || item[field] || "";
}
